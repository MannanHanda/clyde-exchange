-- Login. A user owns the account with the same id as their username.
-- No password, session token or API key is ever stored: only a hash of each, which cannot be turned back
-- into the original. Someone who steals the database still cannot log in as anyone.

CREATE TABLE app_user (
    username      VARCHAR(64)  PRIMARY KEY,
    password_hash VARCHAR(100) NOT NULL,   -- BCrypt: slow on purpose, and salted
    starting_cash BIGINT       NOT NULL,   -- what the account was worth when the user got it; the leaderboard measures from here
    created_at    BIGINT       NOT NULL
);

-- One row per browser that is logged in. The browser holds the token in a cookie; we hold its SHA-256 hash.
CREATE TABLE login_session (
    token_hash VARCHAR(64) PRIMARY KEY,
    username   VARCHAR(64) NOT NULL,
    expires_at BIGINT      NOT NULL
);

-- Keys for a user's own programs (trading bots). key_start is the first few characters, so the user can tell keys apart.
CREATE TABLE api_key (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username   VARCHAR(64) NOT NULL,
    label      VARCHAR(40) NOT NULL,
    key_hash   VARCHAR(64) NOT NULL UNIQUE,
    key_start  VARCHAR(16) NOT NULL,
    created_at BIGINT      NOT NULL
);
