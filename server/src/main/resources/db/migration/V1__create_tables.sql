-- Everything the exchange needs to carry on after a restart.
-- Written in plain standard SQL so the same script runs on H2 (local file) and PostgreSQL (Docker).
-- All money and prices are whole numbers of ticks (pence); all times are milliseconds since 1970 (UTC).

-- Single numbers the exchange must remember, such as the next order id.
CREATE TABLE exchange_meta (
    name         VARCHAR(40) PRIMARY KEY,
    number_value BIGINT      NOT NULL
);

CREATE TABLE account (
    id           VARCHAR(64) PRIMARY KEY,
    bot          BOOLEAN     NOT NULL,
    unlimited    BOOLEAN     NOT NULL,
    cash         BIGINT      NOT NULL,
    realised_pnl BIGINT      NOT NULL
);

-- An account's position in one symbol. qty is negative for a short position.
CREATE TABLE holding (
    account_id VARCHAR(64) NOT NULL,
    symbol     VARCHAR(16) NOT NULL,
    qty        BIGINT      NOT NULL,
    cost       BIGINT      NOT NULL,
    PRIMARY KEY (account_id, symbol)
);

-- Trade history, for traders only. Trades between bots are not kept: the candles summarise them.
CREATE TABLE account_fill (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id VARCHAR(64) NOT NULL,
    order_id   BIGINT      NOT NULL,
    symbol     VARCHAR(16) NOT NULL,
    side       VARCHAR(4)  NOT NULL,
    price      BIGINT      NOT NULL,
    qty        BIGINT      NOT NULL,
    traded_at  BIGINT      NOT NULL
);
CREATE INDEX account_fill_by_account ON account_fill (account_id, id);

-- Traders' orders that were still waiting when the exchange last saved.
CREATE TABLE open_order (
    order_id   BIGINT      PRIMARY KEY,
    account_id VARCHAR(64) NOT NULL,
    symbol     VARCHAR(16) NOT NULL,
    side       VARCHAR(4)  NOT NULL,
    order_type VARCHAR(12) NOT NULL,
    price      BIGINT      NOT NULL,
    stop_price BIGINT      NOT NULL,
    quantity   BIGINT      NOT NULL,
    remaining  BIGINT      NOT NULL
);

-- The last price of each symbol and the statistics of its current trading day.
CREATE TABLE symbol_state (
    symbol         VARCHAR(16) PRIMARY KEY,
    last_price     BIGINT NOT NULL,
    day_start      BIGINT NOT NULL,
    open_price     BIGINT NOT NULL,
    high_price     BIGINT NOT NULL,
    low_price      BIGINT NOT NULL,
    volume         BIGINT NOT NULL,
    previous_close BIGINT NOT NULL
);

-- Price history. interval_seconds is 60 (1-minute candles) or 3600 (1-hour candles).
CREATE TABLE candle (
    symbol           VARCHAR(16) NOT NULL,
    interval_seconds INT         NOT NULL,
    start_time       BIGINT      NOT NULL,
    open_price       BIGINT      NOT NULL,
    high_price       BIGINT      NOT NULL,
    low_price        BIGINT      NOT NULL,
    close_price      BIGINT      NOT NULL,
    volume           BIGINT      NOT NULL,
    PRIMARY KEY (symbol, interval_seconds, start_time)
);

-- symbol is NULL for news about a whole sector.
CREATE TABLE news_item (
    id           BIGINT       PRIMARY KEY,
    published_at BIGINT       NOT NULL,
    symbol       VARCHAR(16),
    sector       VARCHAR(40)  NOT NULL,
    headline     VARCHAR(300) NOT NULL,
    kind         VARCHAR(8)   NOT NULL
);
